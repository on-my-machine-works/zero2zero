def _iface_ipv4(iface: str) -> str:
    try:
        out = subprocess.check_output(
            ["ip", "-4", "-o", "addr", "show", "dev", iface],
            stderr=subprocess.DEVNULL,
            text=True,
            timeout=2.0,
        )
        for tok in out.split():
            if "/" in tok and tok[0].isdigit():
                return tok.split("/", 1)[0]
    except Exception:
        pass
    return ""


def _default_gateway() -> str:
    try:
        out = subprocess.check_output(
            ["ip", "-4", "route", "show", "default"],
            stderr=subprocess.DEVNULL,
            text=True,
            timeout=2.0,
        )
        parts = out.split()
        if "via" in parts:
            idx = parts.index("via")
            if idx + 1 < len(parts):
                return parts[idx + 1]
    except Exception:
        pass
    return ""


def collect_host_vars(extra: Optional[Dict[str, str]] = None) -> Dict[str, str]:
    wlan0 = _iface_ipv4("wlan0")
    wlan1 = _iface_ipv4("wlan1")
    usb0 = _iface_ipv4("usb0")
    primary = wlan0 or usb0 or wlan1 or "127.0.0.1"
    gw = _default_gateway()
    now_local = datetime.now()
    env = {
        "HOST_IP": primary,
        "WLAN0_IP": wlan0 or primary,
        "WLAN1_IP": wlan1,
        "USB0_IP": usb0,
        "GATEWAY": gw,
        "HOSTNAME": socket.gethostname(),
        "UTC_ISO": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "LOCAL_TIME": now_local.strftime("%Y-%m-%d %H:%M:%S"),
    }
    if extra:
        env.update({str(k): str(v) for k, v in extra.items()})
    return env


def render_template_text(template: str, variables: Optional[Dict[str, str]] = None) -> str:
    ctx = collect_host_vars(variables)

    def _repl(match: re.Match[str]) -> str:
        key = match.group(1)
        return ctx.get(key, match.group(0))

    return VAR_PATTERN.sub(_repl, template)


def sanitize_script_filename(name: str) -> str:
    """Normalizes a script basename into a clean `<slug>.txt` for `/ext/badusb/`."""
    base = os.path.basename(name.strip())
    if base.lower().endswith(".txt"):
        base = base[:-4]
    elif base.lower().endswith(".ducky"):
        base = base[:-6]
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "_", base).strip("._-")
    if not cleaned:
        cleaned = "z2z_payload"
    return f"{cleaned}.txt"


def build_ducky_script(
    text: str,
    raw_ducky: bool = False,
    template_expand: bool = True,
    initial_delay_ms: int = 450,
    variables: Optional[Dict[str, str]] = None,
) -> str:
    """Builds a Flipper BadUSB DuckyScript payload from typed text or raw Ducky commands."""
    body = render_template_text(text, variables) if template_expand else text
    lines = [ln.rstrip("\r") for ln in body.splitlines()]
    if raw_ducky:
        out_lines = [ln for ln in lines if ln.strip() != "" or len(lines) == 1]
        return ("\n".join(out_lines).rstrip("\n") + "\n") if out_lines else "REM Empty script\n"

    # Auto-STRINGLN mode: types each line verbatim via Flipper USB HID + ENTER
    script: List[str] = [
        "REM Generated by Zero2Zero on CardputerZero",
        f"DELAY {max(0, int(initial_delay_ms))}",
    ]
    non_empty = [ln for ln in lines if ln != ""]
    if not non_empty:
        script.append("REM (empty text)")
    else:
        for idx, ln in enumerate(lines):
            if idx > 0:
                script.append("DELAY 80")
            if ln:
                script.append(f"STRING {ln}")
            script.append("ENTER")
    return "\n".join(script) + "\n"


def default_studio_dir() -> Path:
    xdg = os.environ.get("XDG_DATA_HOME") or os.path.expanduser("~/.local/share")
    p = Path(xdg) / "zero2zero" / "studio"
    p.mkdir(parents=True, exist_ok=True)
    return p


def list_local_templates(studio_dir: Optional[Path] = None) -> List[Dict[str, object]]:
    base = studio_dir or default_studio_dir()
    if not base.exists():
        return []
    out: List[Dict[str, object]] = []
    for p in sorted(base.iterdir()):
        if p.is_file() and not p.name.startswith("."):
            st = p.stat()
            out.append({"name": p.name, "path": str(p), "size": st.st_size})
    return out
